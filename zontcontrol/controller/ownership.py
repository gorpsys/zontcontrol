"""Whole-device local ownership and synchronous command admission.

The coordination gate is mandatory: local exclusion alone grants no right to
control ZONT. A production gate must validate the current R1/R2 permission.
There is deliberately no local permissive implementation in the application.
Gate I/O and command HTTP never hold the account-wide state lock.
"""

import math
from dataclasses import dataclass, field
from threading import Lock
from typing import Protocol
from uuid import UUID, uuid4

from .contracts import (
    CommandOutcomeUnknown, ControlOwnershipRequired, ControlSession, DeviceControlBusy,
    InvalidArguments, ValidatedCommand,
)
from ..coordination.statistics import error_event, observe


class CoordinationGate(Protocol):
    """Internal DI boundary for executor grants, implemented by coordination.

    owner is generated by the executor binding, never supplied by a consumer.
    try_acquire returns a confirmed session or raises Busy (pending requests
    belong to the gate). validate checks grant identity and current leader token;
    the executor separately checks its local expires_at at final admission.
    release publishes completion only after all reserved work has finished.
    """

    def try_acquire(self, owner: UUID, device_id: int, *, lease_seconds: float
                    ) -> ControlSession: ...

    def validate(self, owner: UUID, session: ControlSession) -> None: ...

    def release(self, owner: UUID, session: ControlSession) -> None: ...


@dataclass
class _Ownership:
    binding: object
    session: ControlSession | None = None
    in_flight: int = 0
    closing: bool = False
    releasing: bool = False
    context: dict = field(default_factory=dict)
    outcome: str = 'success'
    cleanup_observed: bool = False


class CommandExecutor:
    """Shared executor for one account; clock is the local lease clock.

    A binding is issued by the composition root for each consumer. Neither
    lifecycle cancellation nor a registrar deadline is an admission input.
    Expired local ownership remains held until explicit release; it cannot
    authorize commands, including cleanup, or extend the remote grant.
    A failed release reservation may be discarded only after local expiry and
    completion of all in-flight work; no metadata write is retried for this.
    """

    def __init__(self, *, gate: CoordinationGate, clock, statistics=None):
        if gate is None or not callable(clock):
            raise InvalidArguments()
        self._gate = gate
        self._clock = clock
        self._lock = Lock()
        self._devices = {}
        self._statistics = statistics

    def _observe(self, held, event, **fields):
        try:
            observe(self._statistics, event, device_id=held.session.device_id,
                    **held.context, **fields)
        except Exception:
            pass

    def _command_observation(self, held, command, outcome):
        self._observe(held, 'command', phase='command', outcome=outcome)
        if (isinstance(command, ValidatedCommand)
                and command.control_key.kind == 'toggle_buttons' and command.action == 'trigger'
                and dict(command.arguments).get('target_state') is False):
            self._observe(held, 'cleanup', phase='command', outcome=outcome,
                          coverage='partial')

    def bind(self):
        return _ControlBinding(self)

    def _match(self, binding, session, device_id, *, allow_closing=False):
        if not isinstance(session, ControlSession) or session.device_id != device_id:
            raise ControlOwnershipRequired()
        held = self._devices.get(device_id)
        # DTO equality does not confer ownership. Only the issued object and
        # its DI-bound consumer identify this local acquisition.
        if (held is None or held.binding is not binding or held.session is not session
                or held.closing and not allow_closing):
            raise ControlOwnershipRequired()
        return held

    def _acquire(self, binding, device_id, lease_seconds):
        if (type(device_id) is not int or device_id <= 0
                or type(lease_seconds) not in (int, float)):
            raise InvalidArguments()
        try:
            valid = math.isfinite(lease_seconds) and lease_seconds > 0
        except OverflowError:
            valid = False
        if not valid:
            raise InvalidArguments()
        with self._lock:
            held = self._devices.get(device_id)
            if (held is not None and held.closing and not held.releasing
                    and held.in_flight == 0 and held.session is not None
                    and self._clock() >= held.session.expires_at):
                del self._devices[device_id]
                held = None
            if held is not None:
                if held.binding is binding and held.session is not None and not held.closing:
                    return held.session
                raise DeviceControlBusy()
            held = _Ownership(binding)
            self._devices[device_id] = held
        try:
            session = self._gate.try_acquire(binding._owner, device_id,
                                             lease_seconds=lease_seconds)
            if (not isinstance(session, ControlSession) or session.device_id != device_id
                    or not self._clock() < session.expires_at):
                raise ControlOwnershipRequired()
            with self._lock:
                held.session = session
            # Instrumentation is optional and must not affect ownership.
            try:
                context = getattr(self._gate, 'observation_context', None)
                if context is not None:
                    held.context = context(binding._owner, session)
            except Exception:
                pass
            return session
        except BaseException:
            with self._lock:
                del self._devices[device_id]
            raise

    def _release_remote(self, held):
        # Keep the closing reservation while completion is being published.
        # An unconfirmed release leaves it held, rather than risking an overtake.
        with self._lock:
            if self._devices.get(held.session.device_id) is not held:
                # Another acquisition already discarded this expired, idle
                # closing reservation. Never publish/delete for its successor.
                return
            if held.releasing:
                return
            held.releasing = True
            report_cleanup = not held.cleanup_observed
            held.cleanup_observed = True
        if report_cleanup:
            self._observe(held, 'cleanup', phase='session', outcome=held.outcome,
                          coverage='partial')
        try:
            self._gate.release(held.binding._owner, held.session)
        except BaseException:
            with self._lock:
                held.releasing = False
            raise
        with self._lock:
            del self._devices[held.session.device_id]

    def _release(self, binding, session):
        with self._lock:
            device_id = session.device_id if isinstance(session, ControlSession) else None
            held = self._match(binding, session, device_id, allow_closing=True)
            held.closing = True
            release_now = held.in_flight == 0
        if release_now:
            self._release_remote(held)

    def _execute(self, binding, command, session, validate, send):
        with self._lock:
            held = self._match(binding, session, command.device_id)
            # Reserve validation as well as accepted HTTP so release can never
            # hand the device to a new owner while this call is being admitted.
            held.in_flight += 1
        try:
            if not self._clock() < session.expires_at:
                raise ControlOwnershipRequired()
            prepared = validate()
            self._gate.validate(binding._owner, session)
            with self._lock:
                self._match(binding, session, command.device_id)
                if not self._clock() < session.expires_at:
                    raise ControlOwnershipRequired()
                # Accepted here. No subsequent expiry/stop/deadline recheck.
            result = send(prepared)
            self._command_observation(held, command, 'success')
            return result
        except BaseException as error:
            outcome = 'unknown' if isinstance(error, CommandOutcomeUnknown) else 'failure'
            with self._lock:
                if held.outcome != 'unknown':
                    held.outcome = outcome
            self._command_observation(held, command, outcome)
            self._observe(held, error_event(error), phase='command', outcome=outcome)
            raise
        finally:
            with self._lock:
                held.in_flight -= 1
                release_now = held.closing and held.in_flight == 0
            if release_now:
                self._release_remote(held)


class _ControlBinding:
    def __init__(self, executor):
        self._executor = executor
        self._owner = uuid4()

    def try_acquire_control(self, device_id, *, lease_seconds):
        return self._executor._acquire(self, device_id, lease_seconds)

    def release_control(self, session):
        return self._executor._release(self, session)

    def execute(self, command, session, validate, send):
        return self._executor._execute(self, command, session, validate, send)
