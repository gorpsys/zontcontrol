"""Structural dependencies of device coordination."""

from threading import Event
from typing import Protocol
from uuid import UUID

from ..control_types import ControlSession
from .clock import LeaseTiming


class CoordinationGate(Protocol):
    """Internal DI boundary for executor grants, implemented by coordination.

    owner is generated by the executor binding, never supplied by a consumer.
    try_acquire returns a confirmed session or raises Busy (pending requests
    belong to the gate). validate checks grant identity and current leader token;
    the executor separately checks its local expires_at at final admission.
    release publishes completion only after all reserved work has finished.
    """

    def try_acquire(self, owner: UUID, device_id: int, *, lease_seconds: float,
                    request_id: UUID | None = None, local_deadline: float | None = None,
                    attempt_deadline: float | None = None
                    ) -> ControlSession: ...

    def abandon_request(self, owner: UUID, device_id: int, request_id: UUID) -> None: ...

    def validate(self, owner: UUID, session: ControlSession) -> None: ...

    def release(self, owner: UUID, session: ControlSession) -> None: ...


class MetadataPort(Protocol):
    """Read and update only the device metadata used by coordination."""

    def read_metadata(self, device_id: int) -> dict[str, str | None]: ...

    def read_metadata_field(self, device_id: int, field: str) -> str | None: ...

    def update_metadata(self, device_id: int, field: str, value: str) -> None: ...


class CoordinationSettings(Protocol):
    """Already validated timing settings supplied by the composition root."""

    @property
    def delta_seconds(self) -> float: ...

    @property
    def timing(self) -> LeaseTiming: ...


class Clock(Protocol):
    """Local lease clock with interruptible waits."""

    def now(self) -> float: ...

    def wait(self, cancelled: Event, seconds: float) -> bool: ...


class EpochSampler(Protocol):
    """UNIX-seconds source sampled once when creating a v2 leader timeline."""

    def __call__(self) -> float: ...
